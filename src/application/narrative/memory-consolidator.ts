/** Thread statuses that count as "active" for brief and consolidation. */
export const ACTIVE_THREAD_STATUSES: ReadonlySet<PlotThread["status"]> = new Set([
  "open",
  "developing",
  "ready_to_resolve",
]);

/** Setup statuses that are non-terminal (still relevant). */
export const NON_TERMINAL_SETUP_STATUSES: ReadonlySet<SetupPayoff["status"]> = new Set([
  "planned",
  "seeded",
  "reinforced",
  "ready",
]);

// ---------------------------------------------------------------------------
// MemoryConsolidator
// ---------------------------------------------------------------------------

export class MemoryConsolidator {
  private readonly port: MemoryConsolidatorPort | undefined;
  private readonly config: NarrativeConfig;
  private readonly diagnostics: DiagnosticSink;
  /**
   * C2/C8 角色注册表（bootstrap 经 NarrativeDirectorService 注入）。
   * 在场时请求侧构造 §6.2 身份视图（main 接线）；缺席 = legacy。
   */
  private readonly registry: CharacterRegistry | undefined;

  constructor(opts: {
    port: MemoryConsolidatorPort | undefined;
    config: NarrativeConfig;
    /** C8 §6.2：registry 在场时请求携带身份视图与证据投影。 */
    registry?: CharacterRegistry;
    diagnostics?: DiagnosticSink;
  }) {
    this.port = opts.port;
    this.config = opts.config;
    this.registry = opts.registry;
    this.diagnostics = opts.diagnostics ?? silentDiagnosticSink;
  }

  /**
   * Run one consolidation pass: cap events, call the port, filter ops
   * through the validators, generate the episode id.
   *
   * - Events are capped to `max_events_per_call`, keeping the LAST N.
   * - A port failure (or an absent port) yields an empty outcome with
   *   `result: null` — never throws.
   * - opts.priorIssues（M2 §6.2 定向修复）：随请求透传给 port——整批被拒
   *   后 director 携带上一次 issues 重试一次；本函数校验语义不变。
   */
  async consolidate(
    events: StoredEvent[],
    memory: NarrativeMemoryState,
    stateLocation: string,
    stateCharacters: string[],
    opts?: { priorIssues?: readonly IdentityValidationIssue[] },
  ): Promise<ConsolidationOutcome> {
    // No port → empty outcome, nothing called
    if (this.port === undefined) {
      return emptyOutcome();
    }

    if (events.length === 0) {
      return emptyOutcome();
    }

    // Cap events to max_events_per_call (keep the OLDEST N, FIFO — same
    // order the director batches in; this cap is defense in depth).
    const maxEvents = this.config.consolidation.max_events_per_call;
    let batch: StoredEvent[];
    if (events.length > maxEvents) {
      this.diagnostics.info(
        "NarrativeDirector",
        `Dropping ${events.length - maxEvents} newer overflow events from batch (max ${maxEvents})`,
      );
      batch = events.slice(0, maxEvents);
    } else {
      batch = events;
    }

    const fromSeq = batch[0]!.seq;

    // Active threads and non-terminal setups for the consolidator
    const activeThreads = Object.values(memory.threads).filter((t) =>
      ACTIVE_THREAD_STATUSES.has(t.status),
    );
    const nonTerminalSetups = Object.values(memory.setups).filter((s) =>
      NON_TERMINAL_SETUP_STATUSES.has(s.status),
    );

    // --- C8 §6.2 request-side identity view（main 接线）---
    // registry 在场时构造身份视图与记忆证据投影，随 REQUEST 显式携带
    // （计划 §6.2「main 请求必须携带…允许角色及 evidence 范围」；campus
    // 是 adapter 构造后随 ConsolidationResult 回传——校验函数零差异）。
    // adapter 用同一视图渲染权威 ID 段：校验与模型被告知的权威同源。
    // registry 缺席 = legacy：请求不携带，标签不校验身份维度。
    //
    // M2 §6.2：一次选择两处消费——relevantFacts/relevantBeliefs 渲染进
    // 请求（模型看得见的引用 ID），citable*Ids 进身份视图（amend/correct
    // 引用权威）。超预算收缩两者一起缩（绝不要求模型猜库里的 ID）。
    const evidence =
      this.registry !== undefined
        ? projectMemoryEvidence(batch, this.registry)
        : undefined;
    const provisionalView =
      this.registry !== undefined && evidence !== undefined
        ? buildMemoryIdentityView({
            events: batch,
            registry: this.registry,
            stateCharacters,
            stateLocation,
            evidence,
          })
        : undefined;
    const citable = selectCitableReferences({
      facts: memory.facts,
      beliefs: memory.beliefs,
      characters: stateCharacters,
      location: stateLocation,
      factMax: this.config.facts.brief_max,
      // belief 候选上限走 config（facts.brief_max 同一模式）；缺省值与
      // memory-validator 的 MAX_CITABLE_BELIEFS_PER_REQUEST 对齐。
      beliefMax: this.config.beliefs.request_max,
      // identity 模式的 belief 归属权威 = 证据登场 ∪ 场景在场（R27：roster
      // 全集绝不作为归属权威）；legacy 只按场景名单过滤。
      ...(provisionalView !== undefined
        ? { allowedCharacterIds: provisionalView.allowedCharacterIds }
        : {}),
    });
    const identity =
      this.registry !== undefined && evidence !== undefined
        ? buildMemoryIdentityView({
            events: batch,
            registry: this.registry,
            stateCharacters,
            stateLocation,
            evidence,
            citableFactIds: citable.citableFactIds,
            citableBeliefIds: citable.citableBeliefIds,
          })
        : undefined;

    // --- Call consolidator (failure → null result, never throws) ---
    let result: ConsolidationResult;
    try {
      result = await this.port.consolidate({
        events: batch,
        threads: activeThreads,
        setups: nonTerminalSetups,
        stateLocation,
        stateCharacters,
        ...(identity !== undefined ? { identity } : {}),
        ...(evidence !== undefined ? { evidenceEvents: evidence } : {}),
        relevantFacts: citable.relevantFacts,
        relevantBeliefs: citable.relevantBeliefs,
        ...(opts?.priorIssues !== undefined && opts.priorIssues.length > 0
          ? { priorIssues: opts.priorIssues }
          : {}),
      });
    } catch (err) {
      this.diagnostics.warn(
        "NarrativeDirector",
        `consolidation failed: ${String(err)}`,
      );
      return emptyOutcome();
    }

    // --- Filter through the validators transactionally ---
    // Ops are validated in OUTPUT order against a SHADOW copy of the
    // memory: each accepted op is applied to the shadow before the next
    // one is validated, so budgets and state transitions see the ops that
    // came before them in the same batch (two creates against a full
    // budget, seed-then-reinforce, repeated advances...). A rejected op is
    // NOT applied to the shadow. (Audit finding 4.)
    //
    // C8 §6.2: identity/reference validation is explicit. The episode
    // proposal verdict is a ValidatedProposal (accepted — including legal
    // empty proposals — or rejected with code/path/value issues); ops
    // carry structured issues on RejectedOp. There is NO silent tag
    // filtering anywhere (filterCanonicalTags is gone): an illegal tag
    // rejects the whole episode proposal instead of being dropped.
    const view = identity;
    const validationMode: "identity" | "legacy" =
      view !== undefined ? "identity" : "legacy";

    const rejected: RejectedOp[] = [];
    const shadow = structuredClone(memory);
    const batchLastSeq = batch[batch.length - 1]!.seq;

    // Reference authorities for episode tags: exactly the lists rendered
    // into the request (active threads / non-terminal setups), plus thread
    // ids created by same-batch accepted create ops.
    const knownThreadIds = new Set(activeThreads.map((t) => t.id));
    const knownSetupIds = new Set(nonTerminalSetups.map((s) => s.id));

    // 1) Thread ops (existing Task 5 rules; no identity fields on thread ops).
    //    Rejections buffered locally so the Task 6 recording order stays
    //    episode → thread → setup (the episode is validated in step 3 but
    //    must be recorded first).
    const threadRejected: RejectedOp[] = [];
    const threadOps: ThreadOp[] = [];
    for (const op of result.threadOps) {
      const reason = validateThreadOp(op, shadow, this.config);
      if (reason === null) {
        threadOps.push(op);
        if (op.type === "create") {
          knownThreadIds.add(op.id);
        }
        applyThreadOpToState(shadow, op, 0); // checkpoint irrelevant for validation
      } else {
        threadRejected.push({ kind: "thread", op, reason, rule: rejectionRule(reason) });
      }
    }

    // 2) Setup ops: Task 5 rules + §6.2 evidence refs. An op with illegal
    //    evidence is rejected as a whole (its issues are reported, never
    //    silently stripped).
    const setupRejected: RejectedOp[] = [];
    const setupEvidenceIssues: IdentityValidationIssue[] = [];
    const setupOps: SetupOp[] = [];
    result.setupOps.forEach((op, index) => {
      const evidenceIssues =
        view !== undefined
          ? validateEvidenceRefs(
              op.evidenceEventIds ?? [],
              view,
              `setupOps[${index}].evidenceEventIds`,
            )
          : [];
      const reason = validateSetupOp(op, shadow, this.config, batchLastSeq);
      if (reason === null && evidenceIssues.length === 0) {
        setupOps.push(op);
        applySetupOpToState(shadow, op, 0); // checkpoint irrelevant for validation
      } else {
        setupEvidenceIssues.push(...evidenceIssues);
        setupRejected.push({
          kind: "setup",
          op,
          reason:
            reason ??
            `证据事件引用非法（见 issues：${formatIdentityIssues(evidenceIssues, view)}）`,
          ...(reason !== null ? { rule: rejectionRule(reason) } : {}),
          ...(evidenceIssues.length > 0 ? { issues: evidenceIssues } : {}),
        });
      }
    });

    // 3) Episode proposal: shape rules + §6.2 identity/reference tags.
    //    ALL issues are collected (never stops at the first) and reported
    //    together with field paths and offending values.
    const shapeReason = validateEpisodeOp(result.episode);
    const episodeIssues: IdentityValidationIssue[] = [];
    if (view !== undefined) {
      episodeIssues.push(
        ...validateCharacterTags(
          result.episode.characters,
          view,
          "episode.characters",
        ),
        ...validateReferenceTags(
          result.episode.locations,
          view.canonicalLocations,
          "episode.locations",
        ),
      );
    }
    episodeIssues.push(
      ...validateReferenceTags(result.episode.threads, knownThreadIds, "episode.threads"),
      ...validateReferenceTags(result.episode.setups, knownSetupIds, "episode.setups"),
    );

    let episode: EpisodeMemory | null = null;
    let episodeProposal: ValidatedProposal<EpisodeMemory> | undefined;
    if (shapeReason !== null || episodeIssues.length > 0) {
      episodeProposal = rejectedProposal(episodeIssues);
      rejected.push({
        kind: "episode",
        op: result.episode,
        reason:
          shapeReason ??
          `episode 提案身份/引用非法（§6.2）：${formatIdentityIssues(episodeIssues, view)}`,
        ...(shapeReason !== null ? { rule: rejectionRule(shapeReason) } : {}),
        ...(episodeIssues.length > 0 ? { issues: episodeIssues } : {}),
      });
    } else {
      episode = {
        id: `ep_${memory.revision + 1}_${fromSeq}`,
        fromEventSeq: fromSeq,
        toEventSeq: batchLastSeq,
        summary: result.episode.summary,
        characters: result.episode.characters,
        locations: result.episode.locations,
        threads: result.episode.threads,
        setups: result.episode.setups,
        importance: result.episode.importance,
      };
      // 合法提案（含合法空提案 = no-op）：value + 空 issues。
      episodeProposal = acceptedProposal(episode);
    }

    // Rejection recording order stays episode → thread → setup →
    // fact → belief → finding (Task 6 + MA-B).
    rejected.push(...threadRejected, ...setupRejected);

    // 4) MA-B fact/belief/finding filters. M2 §6.2：fact/belief 的身份/
    //    引用校验跑在同一 C8 身份视图上（引用权威 + 批内证据区间 + 知情
    //    链）；身份违规的 op 整条拒绝并计入 identityIssues——director 层
    //    据此整批不提交（§6.2「非法提案整批不提交」）。规则类拒绝（预算/
    //    状态机/形状）仍按 op 记 RejectedOp。
    const factIdentityIssues: IdentityValidationIssue[] = [];
    const beliefIdentityIssues: IdentityValidationIssue[] = [];
    const factOps = this.filterFactOps(
      result,
      shadow,
      memory.revision + 1,
      batchLastSeq,
      rejected,
      view,
      factIdentityIssues,
    );
    const beliefOps = this.filterBeliefOps(
      result,
      shadow,
      stateCharacters,
      memory.revision + 1,
      batchLastSeq,
      rejected,
      view,
      beliefIdentityIssues,
    );
    const findings = this.collectFindings(result, batchLastSeq, rejected);

    // §6.2 身份/引用问题聚合（episode + setup 证据 + M2 fact/belief）。
    const identityIssues: readonly IdentityValidationIssue[] = [
      ...episodeIssues,
      ...setupEvidenceIssues,
      ...factIdentityIssues,
      ...beliefIdentityIssues,
    ];

    return {
      result,
      episode,
      episodeProposal,
      threadOps,
      setupOps,
      factOps,
      beliefOps,
      findings,
      rejected,
      identityIssues,
      validationMode,
    };
  }

  // -------------------------------------------------------------------------
  // Per-op-class validation filters (transactional against `shadow`)
  // -------------------------------------------------------------------------

  private filterFactOps(
    result: ConsolidationResult,
    shadow: NarrativeMemoryState,
    idRevision: number,
    batchLastSeq: number,
    rejected: RejectedOp[],
    view: MemoryIdentityView | undefined,
    identityIssues: IdentityValidationIssue[],
  ): FactOp[] {
    const accepted: FactOp[] = [];
    let establishCount = 0;
    let factSeq = 0;
    result.factOps.forEach((op, index) => {
      // M2 §6.2：amend 引用权威 + 批内证据区间（视图缺席 = legacy 不校验）。
      // 身份与规则两层都跑：拒绝时 rule（规则码）与 issues（§6.2 结构化）
      // 同时保留——身份拒绝不掩盖规则层的精确诊断。
      const issues =
        view !== undefined
          ? validateFactIdentity(op, view, `factOps[${index}]`)
          : [];
      const reason = validateFactOp(op, shadow.facts, batchLastSeq);
      if (issues.length > 0 || reason !== null) {
        identityIssues.push(...issues);
        rejected.push({
          kind: "fact",
          op,
          reason:
            reason ??
            `fact 提案身份/引用非法（§6.2）：${formatIdentityIssues(issues, view)}`,
          ...(reason !== null ? { rule: rejectionRule(reason) } : {}),
          ...(issues.length > 0 ? { issues } : {}),
        });
        return;
      }
      if (op.type === "establish") {
        if (establishCount >= MAX_ESTABLISH_PER_BATCH) {
          rejected.push({
            kind: "fact",
            op,
            reason: "[FACT_BUDGET_EXCEEDED] 每批 establish 上限 3",
            rule: "FACT_BUDGET_EXCEEDED",
          });
          return;
        }
        establishCount += 1;
      }
      // 影子应用：amend 在影子中标 superseded，供后续 op 校验看到（事务性）。
      applyFactOpToState(shadow, op, factId(idRevision, ++factSeq), 0);
      accepted.push(op);
    });
    return accepted;
  }

  private filterBeliefOps(
    result: ConsolidationResult,
    shadow: NarrativeMemoryState,
    stateCharacters: readonly string[],
    idRevision: number,
    batchLastSeq: number,
    rejected: RejectedOp[],
    view: MemoryIdentityView | undefined,
    identityIssues: IdentityValidationIssue[],
  ): BeliefOp[] {
    const accepted: BeliefOp[] = [];
    let beliefSeq = 0;
    const perCharacterOps = new Map<string, number>();
    result.beliefOps.forEach((op, index) => {
      // M2 §6.2：知情链（证据参与 ∪ 场景在场；R27：roster 存在不算）+
      // correct 引用权威 + 批内证据区间。视图缺席 = legacy，知识代理仍是
      // 场景名单（冻结语义）。身份与规则两层都跑：拒绝时 rule（如
      // BELIEF_CORRECT_FOREIGN_TARGET——同角色约束）与 issues 同时保留。
      const issues =
        view !== undefined
          ? validateBeliefIdentity(op, view, `beliefOps[${index}]`)
          : [];
      // identity 模式下知识维度已由视图判定（含严格空集合）；legacy 模式
      // 沿用场景名单代理。规则层（correct 同角色/状态机）双模式一致。
      const knowledgeProxy =
        view !== undefined
          ? []
          : stateCharacters;
      const reason = validateBeliefOp(op, shadow.beliefs, knowledgeProxy, batchLastSeq);
      if (issues.length > 0 || reason !== null) {
        identityIssues.push(...issues);
        rejected.push({
          kind: "belief",
          op,
          reason:
            reason ??
            `belief 提案身份/知情/引用非法（§6.2）：${formatIdentityIssues(issues, view)}`,
          ...(reason !== null ? { rule: rejectionRule(reason) } : {}),
          ...(issues.length > 0 ? { issues } : {}),
        });
        return;
      }
      const count = perCharacterOps.get(op.characterId) ?? 0;
      if (count >= MAX_BELIEF_OPS_PER_CHARACTER_PER_BATCH) {
        rejected.push({
          kind: "belief",
          op,
          reason: "[BELIEF_BUDGET_EXCEEDED] 每角色每批 belief op 上限 2",
          rule: "BELIEF_BUDGET_EXCEEDED",
        });
        return;
      }
      if (op.type !== "correct") {
        // 每角色 active 上限（§6.1：超限拒新保旧）。
        const activeCount = shadow.beliefs.filter(
          (b) => b.characterId === op.characterId && b.status === "active",
        ).length;
        if (activeCount >= this.config.beliefs.max_active_per_character) {
          rejected.push({
            kind: "belief",
            op,
            reason: "[BELIEF_BUDGET_EXCEEDED] 角色 active beliefs 已达上限",
            rule: "BELIEF_BUDGET_EXCEEDED",
          });
          return;
        }
      }
      perCharacterOps.set(op.characterId, count + 1);
      applyBeliefOpToState(shadow, op, beliefId(idRevision, ++beliefSeq), 0);
      accepted.push(op);
    });
    return accepted;
  }

  /** findings 不修改记忆状态：逐条校验 + 批量上限（§9.2）。 */
  private collectFindings(
    result: ConsolidationResult,
    batchLastSeq: number,
    rejected: RejectedOp[],
  ): AuditFinding[] {
    const accepted: AuditFinding[] = [];
    if (result.findings.length > MAX_FINDINGS_PER_BATCH) {
      rejected.push({
        kind: "finding",
        op: result.findings,
        reason: "[FINDING_BATCH_EXCEEDED] 每批 findings 上限 5",
        rule: "FINDING_BATCH_EXCEEDED",
      });
    }
    for (const finding of result.findings.slice(0, MAX_FINDINGS_PER_BATCH)) {
      const reason = validateFinding(finding, batchLastSeq);
      if (reason === null) {
        accepted.push(finding);
      } else {
        rejected.push({ kind: "finding", op: finding, reason, rule: rejectionRule(reason) });
      }
    }
    return accepted;
  }
}

/** 确定性 fact id（revision 派生，重放幂等——与 episode id 同一纪律）。
 * 服务端应用时必须用同一公式重新生成（shadow 校验与应用分离）。 */
export function factId(revision: number, seq: number): string {
  return `fact_${revision}_${seq}`;
}

/** 确定性 belief id。 */
export function beliefId(revision: number, seq: number): string {
  return `belief_${revision}_${seq}`;
}

function emptyOutcome(): ConsolidationOutcome {
  return {
    result: null,
    episode: null,
    episodeProposal: undefined,
    threadOps: [],
    setupOps: [],
    factOps: [],
    beliefOps: [],
    findings: [],
    rejected: [],
    identityIssues: [],
    // 无提案可校验（port 缺席/失败/空批次）：没有身份权威参与。
    validationMode: "legacy",
  };
}
