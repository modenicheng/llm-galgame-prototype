// ---------------------------------------------------------------------------
// Consolidator port (defined in Task 6; implemented here)
// ---------------------------------------------------------------------------

export interface ConsolidationRequest {
  events: StoredEvent[];
  threads: PlotThread[];
  setups: SetupPayoff[];
  stateLocation: string;
  stateCharacters: string[];
}

export interface ConsolidationResult {
  episode: EpisodeSummaryOp;
  threadOps: ThreadOp[];
  setupOps: SetupOp[];
  /** MA-B 扩展（§4）：facts/beliefs/findings 搭载同一 consolidator 调用。 */
  factOps: FactOp[];
  beliefOps: BeliefOp[];
  findings: AuditFinding[];
}

export interface MemoryConsolidatorPort {
  consolidate(request: ConsolidationRequest): Promise<ConsolidationResult>;
}

/** Outcome of one consolidation pass (Task 8). */
export interface ConsolidationOutcome {
  /** Raw consolidator result; null when the consolidator failed. */
  result: ConsolidationResult | null;
  /** Validated episode (id generated by this class); null when rejected. */
  episode: EpisodeMemory | null;
  /** Thread ops that passed validation. */
  threadOps: ThreadOp[];
  /** Setup ops that passed validation. */
  setupOps: SetupOp[];
  /** MA-B：通过校验的 facts/beliefs/findings（预算与逐条校验后）。 */
  factOps: FactOp[];
  beliefOps: BeliefOp[];
  findings: AuditFinding[];
  /** Ops rejected by the validators (Task 5 rules). */
  rejected: RejectedOp[];
}

// ---------------------------------------------------------------------------
// Constants (moved from narrative-director-service.ts)
// ---------------------------------------------------------------------------

/** Thread statuses that count as "active" for brief and consolidation. */
export const ACTIVE_THREAD_STATUSES: ReadonlySet<PlotThread["status"]> = new Set([
  "open",
  "developing",
  "ready_to_resolve",
]);

/** Setup statuses that are non-terminal (still relevant). */
export const NON_TERMINAL_SETUP_STATUSES: ReadonlySet<SetupPayoff["status"]> = new Set([
  "planned",
  "seeded",
  "reinforced",
  "ready",
]);

// ---------------------------------------------------------------------------
// MemoryConsolidator
// ---------------------------------------------------------------------------

export class MemoryConsolidator {
  private readonly port: MemoryConsolidatorPort | undefined;
  private readonly config: NarrativeConfig;
  private readonly diagnostics: DiagnosticSink;

  constructor(opts: {
    port: MemoryConsolidatorPort | undefined;
    config: NarrativeConfig;
    diagnostics?: DiagnosticSink;
  }) {
    this.port = opts.port;
    this.config = opts.config;
    this.diagnostics = opts.diagnostics ?? silentDiagnosticSink;
  }

  /**
   * Run one consolidation pass: cap events, call the port, filter ops
   * through the validators, generate the episode id.
   *
   * - Events are capped to `max_events_per_call`, keeping the LAST N.
   * - A port failure (or an absent port) yields an empty outcome with
   *   `result: null` — never throws.
   */
  async consolidate(
    events: StoredEvent[],
    memory: NarrativeMemoryState,
    stateLocation: string,
    stateCharacters: string[],
  ): Promise<ConsolidationOutcome> {
    // No port → empty outcome, nothing called
    if (this.port === undefined) {
      return emptyOutcome();
    }

    if (events.length === 0) {
      return emptyOutcome();
    }

    // Cap events to max_events_per_call (keep the OLDEST N, FIFO — same
    // order the director batches in; this cap is defense in depth).
    const maxEvents = this.config.consolidation.max_events_per_call;
    let batch: StoredEvent[];
    if (events.length > maxEvents) {
      this.diagnostics.info(
        "NarrativeDirector",
        `Dropping ${events.length - maxEvents} newer overflow events from batch (max ${maxEvents})`,
      );
      batch = events.slice(0, maxEvents);
    } else {
      batch = events;
    }

    const fromSeq = batch[0]!.seq;

    // Active threads and non-terminal setups for the consolidator
    const activeThreads = Object.values(memory.threads).filter((t) =>
      ACTIVE_THREAD_STATUSES.has(t.status),
    );
    const nonTerminalSetups = Object.values(memory.setups).filter((s) =>
      NON_TERMINAL_SETUP_STATUSES.has(s.status),
    );

    // --- Call consolidator (failure → null result, never throws) ---
    let result: ConsolidationResult;
    try {
      result = await this.port.consolidate({
        events: batch,
        threads: activeThreads,
        setups: nonTerminalSetups,
        stateLocation,
        stateCharacters,
      });
    } catch (err) {
      this.diagnostics.warn(
        "NarrativeDirector",
        `consolidation failed: ${String(err)}`,
      );
      return emptyOutcome();
    }

    // --- Filter through the validators transactionally ---
    // Ops are validated in OUTPUT order against a SHADOW copy of the
    // memory: each accepted op is applied to the shadow before the next
    // one is validated, so budgets and state transitions see the ops that
    // came before them in the same batch (two creates against a full
    // budget, seed-then-reinforce, repeated advances...). A rejected op is
    // NOT applied to the shadow. (Audit finding 4.)
    const rejected: RejectedOp[] = [];
    const shadow = structuredClone(memory);
    const batchLastSeq = batch[batch.length - 1]!.seq;

    let episode: EpisodeMemory | null = null;
    const epReason = validateEpisodeOp(result.episode);
    if (epReason === null) {
      // 把 episode 标签裁剪到权威 ID 集合（audit P1-6）：非规范标签（如
      // LLM 自拟中文名）无法被 EpisodeRetriever 精确匹配，属于死数据。
      filterCanonicalTags(result.episode, stateLocation, stateCharacters);
      episode = {
        id: `ep_${memory.revision + 1}_${fromSeq}`,
        fromEventSeq: fromSeq,
        toEventSeq: batchLastSeq,
        summary: result.episode.summary,
        characters: result.episode.characters,
        locations: result.episode.locations,
        threads: result.episode.threads,
        setups: result.episode.setups,
        importance: result.episode.importance,
      };
    } else {
      rejected.push({
        kind: "episode",
        op: result.episode,
        reason: epReason,
        rule: rejectionRule(epReason),
      });
    }

    const threadOps = this.filterThreadOps(result, shadow, rejected);
    const setupOps = this.filterSetupOps(result, shadow, batchLastSeq, rejected);
    const factOps = this.filterFactOps(
      result,
      shadow,
      memory.revision + 1,
      batchLastSeq,
      rejected,
    );
    const beliefOps = this.filterBeliefOps(
      result,
      shadow,
      stateCharacters,
      memory.revision + 1,
      batchLastSeq,
      rejected,
    );
    const findings = this.collectFindings(result, batchLastSeq, rejected);

    return { result, episode, threadOps, setupOps, factOps, beliefOps, findings, rejected };
  }

  // -------------------------------------------------------------------------
  // Per-op-class validation filters (transactional against `shadow`)
  // -------------------------------------------------------------------------

  private filterThreadOps(
    result: ConsolidationResult,
    shadow: NarrativeMemoryState,
    rejected: RejectedOp[],
  ): ThreadOp[] {
    const accepted: ThreadOp[] = [];
    for (const op of result.threadOps) {
      const reason = validateThreadOp(op, shadow, this.config);
      if (reason === null) {
        accepted.push(op);
        applyThreadOpToState(shadow, op, 0); // checkpoint irrelevant for validation
      } else {
        rejected.push({ kind: "thread", op, reason, rule: rejectionRule(reason) });
      }
    }
    return accepted;
  }

  private filterSetupOps(
    result: ConsolidationResult,
    shadow: NarrativeMemoryState,
    batchLastSeq: number,
    rejected: RejectedOp[],
  ): SetupOp[] {
    const accepted: SetupOp[] = [];
    for (const op of result.setupOps) {
      const reason = validateSetupOp(op, shadow, this.config, batchLastSeq);
      if (reason === null) {
        accepted.push(op);
        applySetupOpToState(shadow, op, 0); // checkpoint irrelevant for validation
      } else {
        rejected.push({ kind: "setup", op, reason, rule: rejectionRule(reason) });
      }
    }
    return accepted;
  }

  private filterFactOps(
    result: ConsolidationResult,
    shadow: NarrativeMemoryState,
    idRevision: number,
    batchLastSeq: number,
    rejected: RejectedOp[],
  ): FactOp[] {
    const accepted: FactOp[] = [];
    let establishCount = 0;
    let factSeq = 0;
    for (const op of result.factOps) {
      const reason = validateFactOp(op, shadow.facts, batchLastSeq);
      if (reason !== null) {
        rejected.push({ kind: "fact", op, reason, rule: rejectionRule(reason) });
        continue;
      }
      if (op.type === "establish") {
        if (establishCount >= MAX_ESTABLISH_PER_BATCH) {
          rejected.push({
            kind: "fact",
            op,
            reason: "[FACT_BUDGET_EXCEEDED] 每批 establish 上限 3",
            rule: "FACT_BUDGET_EXCEEDED",
          });
          continue;
        }
        establishCount += 1;
      }
      // 影子应用：amend 在影子中标 superseded，供后续 op 校验看到（事务性）。
      applyFactOpToState(shadow, op, factId(idRevision, ++factSeq), 0);
      accepted.push(op);
    }
    return accepted;
  }

  private filterBeliefOps(
    result: ConsolidationResult,
    shadow: NarrativeMemoryState,
    stateCharacters: readonly string[],
    idRevision: number,
    batchLastSeq: number,
    rejected: RejectedOp[],
  ): BeliefOp[] {
    const accepted: BeliefOp[] = [];
    let beliefSeq = 0;
    const perCharacterOps = new Map<string, number>();
    for (const op of result.beliefOps) {
      const reason = validateBeliefOp(op, shadow.beliefs, stateCharacters, batchLastSeq);
      if (reason !== null) {
        rejected.push({ kind: "belief", op, reason, rule: rejectionRule(reason) });
        continue;
      }
      const count = perCharacterOps.get(op.characterId) ?? 0;
      if (count >= MAX_BELIEF_OPS_PER_CHARACTER_PER_BATCH) {
        rejected.push({
          kind: "belief",
          op,
          reason: "[BELIEF_BUDGET_EXCEEDED] 每角色每批 belief op 上限 2",
          rule: "BELIEF_BUDGET_EXCEEDED",
        });
        continue;
      }
      if (op.type !== "correct") {
        // 每角色 active 上限（§6.1：超限拒新保旧）。
        const activeCount = shadow.beliefs.filter(
          (b) => b.characterId === op.characterId && b.status === "active",
        ).length;
        if (activeCount >= this.config.beliefs.max_active_per_character) {
          rejected.push({
            kind: "belief",
            op,
            reason: "[BELIEF_BUDGET_EXCEEDED] 角色 active beliefs 已达上限",
            rule: "BELIEF_BUDGET_EXCEEDED",
          });
          continue;
        }
      }
      perCharacterOps.set(op.characterId, count + 1);
      applyBeliefOpToState(shadow, op, beliefId(idRevision, ++beliefSeq), 0);
      accepted.push(op);
    }
    return accepted;
  }

  /** findings 不修改记忆状态：逐条校验 + 批量上限（§9.2）。 */
  private collectFindings(
    result: ConsolidationResult,
    batchLastSeq: number,
    rejected: RejectedOp[],
  ): AuditFinding[] {
    const accepted: AuditFinding[] = [];
    if (result.findings.length > MAX_FINDINGS_PER_BATCH) {
      rejected.push({
        kind: "finding",
        op: result.findings,
        reason: "[FINDING_BATCH_EXCEEDED] 每批 findings 上限 5",
        rule: "FINDING_BATCH_EXCEEDED",
      });
    }
    for (const finding of result.findings.slice(0, MAX_FINDINGS_PER_BATCH)) {
      const reason = validateFinding(finding, batchLastSeq);
      if (reason === null) {
        accepted.push(finding);
      } else {
        rejected.push({ kind: "finding", op: finding, reason, rule: rejectionRule(reason) });
      }
    }
    return accepted;
  }
}

/** 确定性 fact id（revision 派生，重放幂等——与 episode id 同一纪律）。
 * 服务端应用时必须用同一公式重新生成（shadow 校验与应用分离）。 */
export function factId(revision: number, seq: number): string {
  return `fact_${revision}_${seq}`;
}

/** 确定性 belief id。 */
export function beliefId(revision: number, seq: number): string {
  return `belief_${revision}_${seq}`;
}

function emptyOutcome(): ConsolidationOutcome {
  return {
    result: null,
    episode: null,
    threadOps: [],
    setupOps: [],
    factOps: [],
    beliefOps: [],
    findings: [],
    rejected: [],
  };
}

/**
 * 把 episode 标签裁剪到权威 ID 集合（audit P1-6）。
 * 集合为空 = 尚无权威（故事开局/event 模式），保留原样；
 * 非空 = 只保留集合内的标签——非规范标签（如 LLM 自拟中文名）无法被
 * EpisodeRetriever 精确匹配，属于死数据。
 */
function filterCanonicalTags(
  op: EpisodeSummaryOp,
  location: string,
  characters: readonly string[],
): void {
  const characterSet = characters.length > 0 ? new Set(characters) : null;
  if (characterSet !== null) {
    op.characters = op.characters.filter((c) => characterSet.has(c));
  }
  if (location !== "") {
    op.locations = op.locations.filter((l) => l === location);
  }
}
