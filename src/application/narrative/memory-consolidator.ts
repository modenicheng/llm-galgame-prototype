export interface ConsolidationRequest {
  events: StoredEvent[];
  threads: PlotThread[];
  setups: SetupPayoff[];
  stateLocation: string;
  stateCharacters: string[];
  /**
   * C8 §6.2 身份视图（main：请求侧携带——campus 由 adapter 构造后随
   * ConsolidationResult 回传，main 按计划 §6.2「main 请求必须携带…允许
   * 角色及 evidence 范围」在请求上显式携带）。MemoryConsolidator 在
   * registry 在场时构造；adapter 用同一视图渲染权威 ID 段，校验与模型
   * 被告知的权威同源。缺席 = legacy（无 registry）。
   *
   * M2 扩展：同一视图携带 fact/belief 引用权威（citableFactIds/
   * citableBeliefIds，与 relevantFacts/relevantBeliefs 候选同源）与批内
   * 证据区间（evidenceBatchSeqRange）。
   */
  identity?: MemoryIdentityView;
  /**
   * C8 §6.2 记忆证据投影（身份稳定事件视图，§5.1 的 projectMemoryEvidence
   * 输出）。请求侧携带：adapter 直接渲染，不再各自投影（与 identity 同
   * 生共死——两者都由本批 events + 同一 registry 派生）。缺席 = legacy。
   */
  evidenceEvents?: readonly ProjectedEvent[];
  /**
   * M2 §6.2：相关既定事实引用（引用 ID + 内容）——prompt 实际提供可引用
   * 的 ID，模型不需要猜库里的 ID。与 identity.citableFactIds 同源（同一
   * 份选择）：超预算收缩时候选与可引用范围一起缩。
   */
  relevantFacts?: readonly FactRecord[];
  /**
   * M2 §6.2：相关角色认知引用（correct 的目标 belief：ID + 角色 + 内容）。
   * 与 identity.citableBeliefIds 同源。
   */
  relevantBeliefs?: readonly BeliefState[];
  /**
   * M2 §6.2 定向修复：上一次尝试的 §6.2 身份/引用问题（director 在整批
   * 拒绝后携带重试一次）。adapter 渲染修复段；校验语义不变。
   */
  priorIssues?: readonly IdentityValidationIssue[];
}

export interface ConsolidationResult {
  episode: EpisodeSummaryOp;
  threadOps: ThreadOp[];
  setupOps: SetupOp[];
  /** MA-B 扩展（§4）：facts/beliefs/findings 搭载同一 consolidator 调用。 */
  factOps: FactOp[];
  beliefOps: BeliefOp[];
  findings: AuditFinding[];
}

export interface MemoryConsolidatorPort {
  consolidate(request: ConsolidationRequest): Promise<ConsolidationResult>;
}

/** Outcome of one consolidation pass (Task 8). */
export interface ConsolidationOutcome {
  /** Raw consolidator result; null when the consolidator failed. */
  result: ConsolidationResult | null;
  /** Validated episode (id generated by this class); null when rejected. */
  episode: EpisodeMemory | null;
  /**
   * §6.2 episode proposal verdict: accepted（value + 空 issues，含合法空
   * 提案 no-op）/ rejected（IdentityValidationIssue[]，字段路径 + 违规值）。
   * undefined = 本次没有待校验提案（port 缺席/失败/无事件）。形状类拒绝
   * （如 summary 超长）不属于身份维度：status 为 rejected 但 issues 为空，
   * 原因见 rejected[].reason。
   */
  episodeProposal: ValidatedProposal<EpisodeMemory> | undefined;
  /** Thread ops that passed validation. */
  threadOps: ThreadOp[];
  /** Setup ops that passed validation. */
  setupOps: SetupOp[];
  /** MA-B：通过校验的 facts/beliefs/findings（预算与逐条校验后）。 */
  factOps: FactOp[];
  beliefOps: BeliefOp[];
  findings: AuditFinding[];
  /** Ops rejected by the validators (Task 5 rules + C8 identity issues). */
  rejected: RejectedOp[];
  /** 本次全部 §6.2 身份/引用问题（episode + ops，按拒绝记录顺序）。 */
  identityIssues: readonly IdentityValidationIssue[];
  /** identity = 提案携带身份视图并按 §6.2 校验；legacy = 无身份权威。 */
  validationMode: "identity" | "legacy";
}

